/* oxlint-disable typescript/prefer-readonly-parameter-types manifest is a read-only snapshot for emit */
import type { AppRouteEntry, AppRouteManifest, RouteSegment } from './types'
import { promises as fs } from 'node:fs'
import path from 'node:path'
import { generateAppRouteManifest } from './routes'

const IDENT = /^[a-z_$][\w$]*$/i

function escapeIdent(name: string): string {
  return IDENT.test(name) ? name : JSON.stringify(name)
}

function paramsTypeFromSegments(segments: readonly RouteSegment[]): string {
  const fields: string[] = []

  for (const segment of segments) {
    if (segment.param == null) continue
    const valueType = segment.type === 'dynamic' ? 'string' : 'readonly string[]'
    fields.push(`readonly ${escapeIdent(segment.param)}: ${valueType}`)
  }

  if (fields.length === 0) return 'Record<string, never>'
  return `{ ${fields.join('; ')} }`
}

function routeParamsEntries(routes: readonly AppRouteEntry[]): string[] {
  const seen = new Set<string>()
  const entries: string[] = []

  for (const route of routes) {
    if (seen.has(route.path)) continue
    seen.add(route.path)
    entries.push(`    ${JSON.stringify(route.path)}: ${paramsTypeFromSegments(route.segments)}`)
  }

  return entries
}

export function generateRouteTypesDts(manifest: AppRouteManifest): string {
  const entries = routeParamsEntries(manifest.routes)
  const routesBody = entries.length > 0 ? `\n${entries.join(',\n')},\n  ` : ''

  return [
    '// Generated by rari. Do not edit.',
    '',
    "declare module 'rari' {",
    '  interface Register {',
    `    routes: {${routesBody}}`,
    '  }',
    '}',
    '',
    'export {}',
    '',
  ].join('\n')
}

export interface WriteAppRouteTypesOptions {
  readonly appDir?: string
  readonly extensions?: readonly string[]
}

export async function writeAppRouteTypes(
  root: string,
  options: WriteAppRouteTypesOptions = {},
): Promise<string | null> {
  const appDir = path.resolve(root, options.appDir ?? 'src/app')

  try {
    await fs.access(appDir)
  } catch {
    return null
  }

  const manifest = await generateAppRouteManifest(appDir, {
    extensions: options.extensions,
  })
  const typesPath = path.join(path.dirname(appDir), 'rari-routes.d.ts')
  await fs.writeFile(typesPath, generateRouteTypesDts(manifest), 'utf-8')
  return typesPath
}
